//! `GET /api/suggest?field=<authors|tags|series|publishers|languages>&q=<text>`: the values that already exist in the
//! catalogue, for the book editor's fields (`cps/static/js/edit-suggest.js`).
//!
//! Only people who may edit (admin or edit role, verified through the session like `/api/whoami`) get an answer, and
//! tag suggestions follow that account's allowed/denied tags exactly like `helper.tags_filters`. Names come back in the
//! form the editor SAVES: authors with `|` shown as `,`, languages by their name in the account's locale (the editor
//! parses `isoLanguages.get_language_code_from_name`, so the code table in `language_names.tsv` is the same data,
//! regenerated by `tools/gen_language_names.py`). Ranking: names that start with the typed text, then names with a word
//! that starts with it, then names that contain it; within a group the most used first. With no text, the most used.

use crate::{AppState, session, settings};
use axum::Router;
use axum::extract::{Query, State};
use axum::http::{HeaderMap, HeaderValue, StatusCode, header};
use axum::response::{IntoResponse, Response};
use axum::routing::get;
use rusqlite::Connection;
use serde_json::json;
use std::collections::HashMap;
use std::sync::{Arc, LazyLock};

const LIMIT: usize = 20;
const TABLE: &str = include_str!("language_names.tsv");

pub fn routes() -> Router<Arc<AppState>> {
    Router::new().route("/api/suggest", get(suggest))
}

/// `locale -> [(ISO 639-2 code, name)]`.
static LANGUAGES: LazyLock<HashMap<&'static str, Vec<(&'static str, &'static str)>>> =
    LazyLock::new(|| {
        let mut table: HashMap<&str, Vec<(&str, &str)>> = HashMap::new();
        for line in TABLE.lines() {
            let mut parts = line.splitn(3, '\t');
            if let (Some(locale), Some(code), Some(name)) =
                (parts.next(), parts.next(), parts.next())
            {
                table.entry(locale).or_default().push((code, name));
            }
        }
        table
    });

/// `isoLanguages.get_language_names(locale)`: the exact locale, then its language part, then English.
pub(crate) fn names_for(locale: &str) -> &'static [(&'static str, &'static str)] {
    let language = locale.split(['_', '-']).next().unwrap_or("en");
    LANGUAGES
        .get(locale)
        .or_else(|| LANGUAGES.get(language))
        .or_else(|| LANGUAGES.get("en"))
        .map_or(&[], Vec::as_slice)
}

#[derive(Debug, PartialEq, Eq)]
pub struct Candidate {
    pub name: String,
    pub count: i64,
}

/// Rank `candidates` against `query`. A prefix beats a word start beats a substring; ties go to the most used, then
/// alphabetical order, so the answer is deterministic.
pub fn rank(candidates: Vec<Candidate>, query: &str) -> Vec<Candidate> {
    let needle = query.trim().to_lowercase();
    let mut scored: Vec<(u8, Candidate)> = candidates
        .into_iter()
        .filter_map(|candidate| {
            if needle.is_empty() {
                return Some((0, candidate));
            }
            let lower = candidate.name.to_lowercase();
            let group = if lower.starts_with(&needle) {
                0
            } else if lower
                .split(|c: char| !c.is_alphanumeric())
                .any(|word| !word.is_empty() && word.starts_with(&needle))
            {
                1
            } else if lower.contains(&needle) {
                2
            } else {
                return None;
            };
            Some((group, candidate))
        })
        .collect();
    scored.sort_by(|(ag, a), (bg, b)| {
        ag.cmp(bg)
            .then(b.count.cmp(&a.count))
            .then_with(|| a.name.cmp(&b.name))
    });
    scored.into_iter().take(LIMIT).map(|(_, c)| c).collect()
}

fn counted(conn: &Connection, sql: &str) -> rusqlite::Result<Vec<Candidate>> {
    let mut statement = conn.prepare(sql)?;
    let rows = statement.query_map([], |row| {
        Ok(Candidate {
            name: row.get(0)?,
            count: row.get(1)?,
        })
    })?;
    rows.collect()
}

/// `current_user.list_denied_tags()` shape: comma separated, trimmed, `[""]` meaning "no restriction".
fn tag_list(value: &str) -> Vec<String> {
    value.split(',').map(|tag| tag.trim().to_owned()).collect()
}

/// Everything the field can currently offer, before ranking.
fn candidates(
    conn: &Connection,
    field: &str,
    locale: &str,
    denied: &str,
    allowed: &str,
) -> rusqlite::Result<Vec<Candidate>> {
    match field {
        "authors" => Ok(counted(
            conn,
            "SELECT a.name, count(l.id) FROM authors a LEFT JOIN books_authors_link l ON l.author = a.id GROUP BY a.id",
        )?
        .into_iter()
        .map(|c| Candidate {
            // The editor's field reads `Doe, John`; storage keeps `Doe| John`.
            name: c.name.replace('|', ","),
            count: c.count,
        })
        .collect()),
        "tags" => {
            let denied = tag_list(denied);
            let allowed = tag_list(allowed);
            let no_denied = denied == [""];
            let no_allowed = allowed == [""];
            Ok(counted(
                conn,
                "SELECT t.name, count(l.id) FROM tags t LEFT JOIN books_tags_link l ON l.tag = t.id GROUP BY t.id",
            )?
            .into_iter()
            .filter(|c| (no_allowed || allowed.contains(&c.name)) && (no_denied || !denied.contains(&c.name)))
            .collect())
        }
        "series" => counted(
            conn,
            "SELECT s.name, count(l.id) FROM series s LEFT JOIN books_series_link l ON l.series = s.id GROUP BY s.id",
        ),
        "publishers" => counted(
            conn,
            "SELECT p.name, count(l.id) FROM publishers p LEFT JOIN books_publishers_link l ON l.publisher = p.id GROUP BY p.id",
        ),
        "languages" => {
            let used: HashMap<String, i64> = counted(
                conn,
                "SELECT g.lang_code, count(l.id) FROM languages g LEFT JOIN books_languages_link l ON l.lang_code = g.id GROUP BY g.id",
            )?
            .into_iter()
            .map(|c| (c.name, c.count))
            .collect();
            // Every language the editor can save, the ones this library uses first (their count ranks them).
            Ok(names_for(locale)
                .iter()
                .map(|(code, name)| Candidate {
                    name: (*name).to_owned(),
                    count: used.get(*code).copied().unwrap_or(0),
                })
                .collect())
        }
        _ => Ok(Vec::new()),
    }
}

fn locale_of(app_db: &std::path::Path, user_id: i64) -> String {
    settings::open_read_only(app_db)
        .and_then(|conn| {
            conn.query_row("SELECT locale FROM user WHERE id = ?1", [user_id], |row| {
                row.get::<_, Option<String>>(0)
            })
        })
        .ok()
        .flatten()
        .filter(|locale| !locale.is_empty())
        .unwrap_or_else(|| "en".to_owned())
}

fn json_response(status: StatusCode, body: String) -> Response {
    let mut response = (status, body).into_response();
    let headers = response.headers_mut();
    headers.insert(
        header::CONTENT_TYPE,
        HeaderValue::from_static("application/json"),
    );
    headers.insert(
        header::CACHE_CONTROL,
        HeaderValue::from_static("private, no-store"),
    );
    headers.insert(
        header::HeaderName::from_static("cloudflare-cdn-cache-control"),
        HeaderValue::from_static("no-store"),
    );
    headers.insert(header::VARY, HeaderValue::from_static("Cookie"));
    response
}

async fn suggest(
    State(state): State<Arc<AppState>>,
    headers: HeaderMap,
    Query(query): Query<HashMap<String, String>>,
) -> Response {
    let Ok(settings) = state.settings().await else {
        return json_response(StatusCode::SERVICE_UNAVAILABLE, "{}".into());
    };
    let access = match session::identify(&state, &settings, &headers).await {
        Ok(session::Who::User(access)) if crate::whoami::can_edit(access.role) => access,
        Ok(session::Who::User(_)) => return json_response(StatusCode::FORBIDDEN, "{}".into()),
        _ => return json_response(StatusCode::UNAUTHORIZED, "{}".into()),
    };
    let field = query.get("field").cloned().unwrap_or_default();
    let text = query.get("q").cloned().unwrap_or_default();
    if !["authors", "tags", "series", "publishers", "languages"].contains(&field.as_str()) {
        return json_response(StatusCode::BAD_REQUEST, "{}".into());
    }
    let (app_db, metadata) = (state.app_db.clone(), settings.metadata_db());
    let found = tokio::task::spawn_blocking(move || {
        let locale = locale_of(&app_db, access.id);
        let conn = settings::open_read_only(&metadata)?;
        candidates(&conn, &field, &locale, &access.denied, &access.allowed)
            .map(|all| rank(all, &text))
    })
    .await;
    match found {
        Ok(Ok(items)) => json_response(
            StatusCode::OK,
            json!({
                "items": items
                    .iter()
                    .map(|c| json!({"name": c.name, "count": c.count}))
                    .collect::<Vec<_>>()
            })
            .to_string(),
        ),
        Ok(Err(error)) => {
            tracing::error!("suggest failed: {error}");
            json_response(StatusCode::INTERNAL_SERVER_ERROR, "{}".into())
        }
        Err(error) => {
            tracing::error!("suggest task failed: {error}");
            json_response(StatusCode::INTERNAL_SERVER_ERROR, "{}".into())
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn c(name: &str, count: i64) -> Candidate {
        Candidate {
            name: name.into(),
            count,
        }
    }

    fn names(list: &[Candidate]) -> Vec<&str> {
        list.iter().map(|c| c.name.as_str()).collect()
    }

    #[test]
    fn a_prefix_beats_a_word_start_beats_a_substring_and_use_breaks_ties() {
        let ranked = rank(
            vec![
                c("Sejarah Nasional", 5),
                c("Nasional", 1),
                c("Pembangunan nasionalisme", 9),
                c("Internasional", 50),
                c("Nasionalisme Baru", 3),
                c("Unrelated", 100),
            ],
            "nasional",
        );
        assert_eq!(
            names(&ranked),
            // prefixes first (most used first), then a word that starts with it (9 uses before 5), then a substring
            vec![
                "Nasionalisme Baru",
                "Nasional",
                "Pembangunan nasionalisme",
                "Sejarah Nasional",
                "Internasional"
            ]
        );
    }

    #[test]
    fn matching_ignores_case_including_non_ascii_and_empty_text_returns_the_most_used() {
        let ranked = rank(vec![c("Évariste", 1), c("zed", 7), c("Ada", 3)], "é");
        assert_eq!(names(&ranked), vec!["Évariste"]);
        let top = rank(vec![c("b", 1), c("a", 1), c("c", 9)], "  ");
        assert_eq!(
            names(&top),
            vec!["c", "a", "b"],
            "most used, then alphabetical"
        );
    }

    #[test]
    fn at_most_twenty_come_back() {
        let many: Vec<Candidate> = (0..100).map(|n| c(&format!("tag {n}"), n)).collect();
        assert_eq!(rank(many, "tag").len(), LIMIT);
    }

    #[test]
    fn languages_are_named_in_the_locale_the_editor_parses() {
        let id = names_for("id");
        assert!(id.contains(&("ind", "Bahasa Indonesia")));
        assert!(id.contains(&("nld", "Belanda")));
        let en = names_for("en");
        assert!(en.contains(&("ind", "Indonesian")));
        // an unknown locale falls back to English like `get_language_names` plus Flask's default
        assert!(names_for("xx").contains(&("ind", "Indonesian")));
        // `pt_BR` exists as its own table; `pt_PT` falls back to the language part
        assert!(names_for("pt_PT").iter().any(|(code, _)| *code == "ind"));
    }

    fn library() -> Connection {
        let conn = Connection::open_in_memory().unwrap();
        conn.execute_batch(
            "CREATE TABLE authors (id INTEGER PRIMARY KEY, name TEXT);
             CREATE TABLE books_authors_link (id INTEGER PRIMARY KEY, book INTEGER, author INTEGER);
             CREATE TABLE tags (id INTEGER PRIMARY KEY, name TEXT);
             CREATE TABLE books_tags_link (id INTEGER PRIMARY KEY, book INTEGER, tag INTEGER);
             CREATE TABLE series (id INTEGER PRIMARY KEY, name TEXT);
             CREATE TABLE books_series_link (id INTEGER PRIMARY KEY, book INTEGER, series INTEGER);
             CREATE TABLE publishers (id INTEGER PRIMARY KEY, name TEXT);
             CREATE TABLE books_publishers_link (id INTEGER PRIMARY KEY, book INTEGER, publisher INTEGER);
             CREATE TABLE languages (id INTEGER PRIMARY KEY, lang_code TEXT);
             CREATE TABLE books_languages_link (id INTEGER PRIMARY KEY, book INTEGER, lang_code INTEGER);
             INSERT INTO authors VALUES (1, 'Doe| John'), (2, 'Unused Person');
             INSERT INTO books_authors_link (book, author) VALUES (1, 1), (2, 1);
             INSERT INTO tags VALUES (1, 'open'), (2, 'secret'), (3, 'other');
             INSERT INTO books_tags_link (book, tag) VALUES (1, 1), (1, 2), (2, 2);
             INSERT INTO languages VALUES (1, 'ind'), (2, 'eng');
             INSERT INTO books_languages_link (book, lang_code) VALUES (1, 1), (2, 1), (3, 2);",
        )
        .unwrap();
        conn
    }

    #[test]
    fn authors_come_back_the_way_the_editor_reads_and_saves_them() {
        let all = candidates(&library(), "authors", "en", "", "").unwrap();
        let ranked = rank(all, "doe");
        assert_eq!(names(&ranked), vec!["Doe, John"], "`|` is shown as `,`");
        assert_eq!(ranked[0].count, 2);
    }

    #[test]
    fn tag_suggestions_follow_the_accounts_allowed_and_denied_tags() {
        let conn = library();
        let tags = |denied, allowed| {
            let mut found: Vec<String> = candidates(&conn, "tags", "en", denied, allowed)
                .unwrap()
                .into_iter()
                .map(|c| c.name)
                .collect();
            found.sort();
            found
        };
        assert_eq!(tags("", ""), vec!["open", "other", "secret"]);
        assert_eq!(
            tags("secret", ""),
            vec!["open", "other"],
            "denied tags are never offered"
        );
        assert_eq!(
            tags("", "open, other"),
            vec!["open", "other"],
            "an allow list restricts"
        );
        assert_eq!(
            tags("open", "open, secret"),
            vec!["secret"],
            "denied wins over allowed"
        );
    }

    #[test]
    fn languages_the_library_uses_come_first() {
        let all = candidates(&library(), "languages", "id", "", "").unwrap();
        let top = rank(all, "");
        assert_eq!(names(&top)[..2], ["Bahasa Indonesia", "Inggris"]);
        let typed = rank(
            candidates(&library(), "languages", "en", "", "").unwrap(),
            "ind",
        );
        assert_eq!(names(&typed)[0], "Indonesian");
    }

    #[test]
    fn an_unknown_field_offers_nothing() {
        assert!(
            candidates(&library(), "title", "en", "", "")
                .unwrap()
                .is_empty()
        );
    }
}
