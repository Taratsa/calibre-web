//! Werkzeug's password hashes, verified byte for byte: `cps` stores `scrypt:<n>:<r>:<p>$<salt>$<hex>` (scrypt is
//! werkzeug 3's default) with the legacy `pbkdf2:<hash>:<iterations>$…` form still accepted. The digest is
//! `hashlib.scrypt(password, salt=salt, n=n, r=r, p=p, maxmem=132*n*r*p)` hex-encoded, and `hashlib.pbkdf2_hmac`,
//! so a stored hash produced by Flask verifies here without ever re-hashing the other way.

/// The number of bytes `hashlib.scrypt`/`hashlib.pbkdf2_hmac` derive by default (dklen).
const DIGEST_BYTES: usize = 64;

/// Any password whose hash cannot be parsed is refused here and logged; a user must then be given a new password
/// through the admin UI rather than being let in on a guess.
pub fn verify(stored: &str, password: &str) -> bool {
    let mut parts = stored.split('$');
    let (Some(method), Some(salt), Some(expected)) = (parts.next(), parts.next(), parts.next())
    else {
        tracing::error!("stored password hash is not in werkzeug's `method$salt$hash` form");
        return false;
    };
    if parts.next().is_some() {
        tracing::error!("stored password hash has extra `$` fields");
        return false;
    }
    let expected = expected.to_ascii_lowercase();
    if expected.is_empty()
        || expected.len() % 2 != 0
        || expected.len() > DIGEST_BYTES * 2
        || !expected.bytes().all(|b| b.is_ascii_hexdigit())
    {
        tracing::error!("stored password hash has an unexpected digest length");
        return false;
    }
    let Some(actual) = derive(method, salt, password) else {
        return false;
    };
    // Constant time over equal-length lower-case hex; a different length is a mismatch.
    if actual.len() != expected.len() {
        return false;
    }
    let mut difference = 0u8;
    for (left, right) in actual.as_bytes().iter().zip(expected.as_bytes()) {
        difference |= left ^ right;
    }
    difference == 0
}

/// `method` is `scrypt[:n:r:p]` or `pbkdf2[:hash[:iterations]]`, as werkzeug writes it.
fn derive(method: &str, salt: &str, password: &str) -> Option<String> {
    let (name, arguments) = method.split_once(':').map_or((method, ""), |(n, a)| (n, a));
    match name {
        "scrypt" => {
            // werkzeug's argument is `n`, the CPU/memory cost itself (default 2**15), not its log2.
            let (log_n, r, p) = match arguments {
                "" => (15u8, 8u32, 1u32),
                _ => {
                    let mut values = arguments.split(':');
                    let n = values.next()?.parse::<u32>().ok()?;
                    let r = values.next()?.parse::<u32>().ok()?;
                    let p = values.next()?.parse::<u32>().ok()?;
                    (u8::try_from(n.checked_ilog2()?).ok()?, r, p)
                }
            };
            let params = scrypt::Params::new(log_n, r, p).ok()?;
            let mut digest = [0u8; DIGEST_BYTES];
            scrypt::scrypt(password.as_bytes(), salt.as_bytes(), &params, &mut digest).ok()?;
            Some(hex::encode(digest))
        }
        "pbkdf2" => {
            let (hash_name, iterations) = match arguments {
                "" => ("sha256", 1_000_000u32),
                _ => match arguments.split_once(':') {
                    Some((hash_name, iterations)) => (hash_name, iterations.parse::<u32>().ok()?),
                    None => (arguments, 1_000_000u32),
                },
            };
            // `hashlib.pbkdf2_hmac` defaults to the hash's own digest size (32 for sha256, not 64).
            let mut digest = vec![
                0u8;
                match hash_name {
                    "sha1" => 20,
                    "sha512" => 64,
                    _ => 32,
                }
            ];
            match hash_name {
                "sha256" => pbkdf2::pbkdf2_hmac::<sha2::Sha256>(
                    password.as_bytes(),
                    salt.as_bytes(),
                    iterations,
                    &mut digest,
                ),
                "sha1" => pbkdf2::pbkdf2_hmac::<sha1::Sha1>(
                    password.as_bytes(),
                    salt.as_bytes(),
                    iterations,
                    &mut digest,
                ),
                "sha512" => pbkdf2::pbkdf2_hmac::<sha2::Sha512>(
                    password.as_bytes(),
                    salt.as_bytes(),
                    iterations,
                    &mut digest,
                ),
                other => {
                    tracing::error!("unsupported pbkdf2 hash {other}");
                    return None;
                }
            }
            Some(hex::encode(digest))
        }
        other => {
            tracing::error!("unsupported password hash method {other}");
            None
        }
    }
}

#[cfg(test)]
mod tests {
    use super::verify;

    /// Generated by `werkzeug.security.generate_password_hash("correct horse")` in the app image.
    const STORED: &str = "scrypt:32768:8:1$1yLzFeV2rbxMEaDC$948a24aa72cd2c4e8a079a0417a5140870e49c11175916e081f85da20862a206b2b8a881e821aa50c92e5d6405bdd39939e36c2ee9463a9f93cf6a8e474d0180";

    #[test]
    fn verifies_a_werkzeug_scrypt_hash() {
        assert!(verify(STORED, "correct horse"));
        assert!(!verify(STORED, "correct horse "));
        assert!(!verify(STORED, ""));
    }

    #[test]
    fn refuses_malformed_hashes() {
        for bad in [
            "",
            "scrypt",
            "scrypt$x$y",
            "argon2id$s$h",
            "scrypt:32768:8:1$s$zz",
        ] {
            assert!(!verify(bad, "anything"), "{bad}");
        }
    }

    /// `werkzeug.security.generate_password_hash("rahasia", "pbkdf2:sha256:600000")` in the app image.
    #[test]
    fn verifies_a_werkzeug_pbkdf2_hash() {
        let stored = "pbkdf2:sha256:600000$1IAjuDod2iccafFy$f07f11c4bb28bbc1662fc7f0cfaf2dcca6ecbf718d1019355ea0f42b5f566f09";
        assert!(verify(stored, "rahasia"));
        assert!(!verify(stored, "rahasia2"));
    }
}
